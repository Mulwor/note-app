-- * Задача №11 
-- ? Посчитайте стоимость заказа, в котором будут три пачки сухариков, 
-- ? две пачки чипсов и один энергетический напиток. Колонку с 
-- ? рассчитанной стоимостью заказа назовите order_price.
-- ? Для расчётов используйте таблицу products и поле назовите order_price.
SELECT
    SUM(
        CASE
        WHEN name = 'энергетический напиток' THEN price
        WHEN name = 'чипсы' THEN price * 2
        WHEN name = 'сухарики' THEN price * 3
        END
    ) as order_price
from products
WHERE name IN('чипсы', 'энергетический напиток', 'сухарики')


SELECT sum(case when name = 'сухарики' then price * 3
                when name = 'чипсы' then price * 2
                when name = 'энергетический напиток' then price
                else 0 end) as order_price
FROM   products




