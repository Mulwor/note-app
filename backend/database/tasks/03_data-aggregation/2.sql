-- ? молодого курьера мужского пола в таблице couriers. Возраст выразите
-- ? количеством лет, месяцев и дней (как в примере выше), переведя в VARCHAR
-- ? В качестве даты, относительно которой считать возраст курьеров, используйте 
-- ? свою текущую дату (либо не указывайте её на месте первого аргумента, как показано 
-- ? в примерах). Полученную колонку со значением возраста назовите min_age.
-- ? Поле в результирующей таблице: min_age

SELECT AGE(current_date, birth_date)::VARCHAR as min_age
FROM couriers
WHERE sex = 'male' AND birth_date is not NULL
ORDER BY birth_date desc
LIMIT 1


SELECT min(age(birth_date))::varchar as min_age
FROM   couriers
WHERE  sex = 'male'



