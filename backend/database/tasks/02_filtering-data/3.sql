-- * Задача №13
-- ? Из таблицы user_actions получите id всех заказов, сделанных пользователями 
-- ? сервиса в августе 2022 года. Результат отсортируйте по возрастанию id заказа.
-- ? Поле в результирующей таблице: order_id

-- ! Лучшее решение
SELECT order_id
FROM   user_actions
WHERE  action = 'create_order'
   and date_part('month', time) = 8
   and date_part('year', time) = 2022
ORDER BY order_id

-- ! Иное решение
SELECT order_id FROM user_actions
WHERE DATE_PART('month', time) = 08 AND action = 'create_order'
ORDER BY order_id asc



