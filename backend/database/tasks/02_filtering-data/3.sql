-- * Задача №14
-- ? Из таблицы couriers отберите id всех курьеров, родившихся в период 
-- ? с 1990 по 1995 год включительно.
-- ? Результат отсортируйте по возрастанию id курьера.
-- ? Поле в результирующей таблице: courier_id

-- ! Лучшее решение
SELECT courier_id FROM couriers
WHERE DATE_PART('year', birth_date) BETWEEN 1990 AND 1995
ORDER BY courier_id

-- ! Иное решение
SELECT courier_id FROM couriers
WHERE DATE_PART('year', birth_date) >= 1990 AND DATE_PART('year', birth_date) <= 1995
ORDER BY courier_id


-- ! ==============================================================
-- * Задача №15
-- ? Из таблицы user_actions получите информацию о всех отменах заказов, 
-- ? которые пользователи совершали в течение августа 2022 года по средам с
-- ? 12:00 до 15:59:59. Результат отсортируйте по убыванию id отменённых 
-- ? заказов. Поля в результирующей таблице: user_id, order_id, action, time


SELECT user_id, order_id, action, time FROM user_actions
WHERE 
  DATE_PART('year', time) = 2022 AND 
  DATE_PART('month', time) = 08 AND 
  -- Дни недели 3.00 - среда
  DATE_PART('dow', time) = 3.00 AND 
  -- Час с 12:00 по 15:59:59 включительно
  DATE_PART('hour', time) BETWEEN 12 AND 15 AND 
  action = 'cancel_order'
ORDER BY order_id desc


